// Notebook Compiler Environment — Stage 1 (host-side, zero tc change)
//
// 设计依据：docs/notebook.md（Model C：单 .tc + cell 块 + 自上而下可见 + 不隔离）。
// 本 Stage 在 tc 接入 `cell` 关键字前，用 host 侧切分等价获得该语义：
//   - 各 cell 源按顺序拼接为单一 notebook.tc（单 Module，自上而下可见，不隔离）
//   - 跨 cell 值因共享地址空间直接按符号引用，无需序列化
//   - 增量缓存（S1 粗粒度）：整本内容哈希命中则跳过重编
//   - 每 cell 末值经注入的 @main 内联打印，host 用 [[NB:<id>]] 标记按 cell 切分输出
//
// 本文件可被命令行调用（node tools/notebook.mjs run|gen <x.nb.json>），
// 也可被 import 复用：runNotebookObject(nb) / genSource(nb) / inferKind(cell)。
//
// 注：真正的「按 cell 二进制缓存」(emit-ll 粒度下放至 cell) 是 tc 侧增强
//     （见 docs/notebook.md §6 / §13.7），本 Stage 仅做整本哈希缓存以验证闭环。

import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import * as fs from 'node:fs';
import * as path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const execFileP = promisify(execFile);

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const TC_BIN = process.env.TC_BIN || path.join(ROOT, 'out', 'dbg', 'tc.exe');
const OUT_DIR = (name) => path.join(ROOT, 'out', 'notebook', name);

// ---- cell 类型自动识别（允许 JSON 显式覆盖） -----------------------------------
const DECL_RE = /^\s*(fn|struct|variant|flag|union|enum|type|var|const|let|auto|import|export)\b/;
export function inferKind(cell) {
  if (cell.kind) return cell.kind;
  const s = cell.source.trim();
  if (DECL_RE.test(s)) return 'decl';
  // 含分号/大括号的视为语句块
  if (/[;{}]/.test(s) && !/^[^(]*\([^)]*\)\s*$/.test(s)) return 'stmt';
  return 'expr';
}

// ---- 生成单一 notebook.tc -------------------------------------------------------
// decl 细胞 -> 顶层原样（函数/带标注的全局声明）；expr/stmt 细胞 -> 全部进 @main
// 作局部（局部 var 可类型推断，规避顶层须标注的限制）。自上而下顺序保留，
// 跨 cell 引用因同处 @main 作用域直接按符号可见，无需序列化（Model C 单 module）。
// 每个细胞注射一个 [[NB:<id>]] 标记，使 host 能按 cell 切分 stdout 输出。
export function genSource(nb) {
  const top = [];
  const mainBody = [];
  nb.cells.forEach((cell, i) => {
    const kind = inferKind(cell);
    const id = cell.id || `c${i + 1}`;
    const src = cell.source.trim().replace(/;?\s*$/, '');
    mainBody.push(`print("[[NB:${id}]]");`);
    if (kind === 'decl') {
      top.push(src.endsWith(';') ? src : src + ';');
    } else if (kind === 'stmt') {
      mainBody.push(src + ';');
    } else {
      mainBody.push(`var ${id} = (${src});`);
      if (cell.display === 'str') {
        mainBody.push(`print(${id});`);
      } else {
        mainBody.push(`print(int_to_str(${id}));`);
      }
      mainBody.push('print("\\n");');
    }
  });
  mainBody.push('print("[[NB:__END__]]");');
  mainBody.push('return 0;');
  return [
    '// === generated by tools/notebook.mjs (Stage 1, host-side) ===',
    '// Model C: single .tc, cells concatenated top-down, no isolation',
    ...top,
    'pub @main fn nb_main() i32 {',
    ...mainBody.map((l) => '  ' + l),
    '}',
    '',
  ].join('\n');
}

// 把 runner 的 stdout 按 [[NB:<id>]] 标记切成 { id: 该 cell 的原始输出 }
function splitCellOutput(stdout) {
  const map = {};
  const re = /\[\[NB:([A-Za-z0-9_]+)\]\]/g;
  let m;
  let curId = null;
  let start = 0;
  while ((m = re.exec(stdout))) {
    if (curId !== null) map[curId] = stdout.slice(start, m.index);
    curId = m[1];
    start = re.lastIndex;
  }
  if (curId !== null) map[curId] = stdout.slice(start);
  return map;
}

export function hash(s) {
  return createHash('sha256').update(s).digest('hex').slice(0, 16);
}

async function runTc(args, label) {
  try {
    const { stdout, stderr } = await execFileP(TC_BIN, args, { cwd: ROOT, maxBuffer: 10 * 1024 * 1024 });
    return { stdout, stderr, ok: true };
  } catch (err) {
    return { stdout: err.stdout || '', stderr: err.stderr || String(err), ok: false };
  }
}

async function runExe(exePath) {
  try {
    const { stdout, stderr } = await execFileP(exePath, [], { cwd: ROOT, maxBuffer: 10 * 1024 * 1024 });
    return { stdout, stderr, ok: true };
  } catch (err) {
    return { stdout: err.stdout || '', stderr: err.stderr || String(err), ok: false };
  }
}

// ---- 核心：接受 notebook 对象（内存），编译运行并返回每 cell 输出 --------------
// nb: { name?, cells: [{ id?, kind?, source, display? }] }
// 返回：{ name, ok, cached?, cells:[{id,kind,display,output}], stdout?, stage?, detail? }
export async function runNotebookObject(nb) {
  const name = nb.name || 'scratch';
  const dir = OUT_DIR(name);
  fs.mkdirSync(dir, { recursive: true });

  const src = genSource(nb);
  const tcPath = path.join(dir, 'notebook.tc');
  fs.writeFileSync(tcPath, src);

  const buildOut = path.join(dir, 'runner'); // tc 自行补 .exe → runner.exe
  const exePath = path.join(dir, 'runner.exe');
  const h = hash(src);
  const hashPath = path.join(dir, '.hash');
  const cached = fs.existsSync(hashPath) && fs.readFileSync(hashPath, 'utf8') === h && fs.existsSync(exePath);

  let build = { ok: true, stderr: '' };
  if (!cached) {
    build = await runTc(['build', tcPath, '--output', buildOut], 'build');
    if (!build.ok) {
      fs.writeFileSync(path.join(dir, 'build.err'), build.stderr + build.stdout);
      return { name, ok: false, stage: 'build', detail: build.stderr + build.stdout, cells: nb.cells.map((c, i) => ({ id: c.id || `c${i + 1}`, kind: inferKind(c) })) };
    }
    fs.writeFileSync(hashPath, h);
  } else {
    console.log(`[notebook:${name}] cache hit (${h}) — skip rebuild`);
  }

  const run = await runExe(exePath);
  if (!run.ok) {
    return { name, ok: false, stage: 'run', detail: run.stderr + run.stdout, cells: nb.cells.map((c, i) => ({ id: c.id || `c${i + 1}`, kind: inferKind(c) })) };
  }

  fs.writeFileSync(path.join(dir, 'out.txt'), run.stdout);
  const map = splitCellOutput(run.stdout);
  const cells = nb.cells.map((c, i) => {
    const id = c.id || `c${i + 1}`;
    const kind = inferKind(c);
    const output = (map[id] ?? '').replace(/\n+$/, '');
    return { id, kind, display: c.display || 'int', output };
  });

  return { name, ok: true, cached, cells, stdout: run.stdout };
}

// ---- 文件入口封装（供命令行复用） ----------------------------------------------
export async function buildAndRun(nbPath) {
  const abs = path.resolve(nbPath);
  const nb = JSON.parse(fs.readFileSync(abs, 'utf8'));
  const r = await runNotebookObject(nb);
  if (!r.ok) {
    console.error(`[notebook:${r.name}] ${r.stage.toUpperCase()} FAILED`);
    console.error(r.detail);
    return r;
  }
  console.log(`[notebook:${r.name}] ${r.cached ? 'cache hit' : 'built + ran'}`);
  for (const c of r.cells) {
    const shown = c.kind === 'decl' ? '(defined)' : (c.output || '(no output)');
    console.log(`# ${c.id} (${c.kind}): ${shown}`);
  }
  return r;
}

// ---- CLI（仅直接运行时执行） --------------------------------------------------
const isMain = path.resolve(process.argv[1] || '') === fileURLToPath(import.meta.url);
if (isMain) {
  const [cmd, arg] = process.argv.slice(2);
  if (cmd === 'run' && arg) {
    const r = await buildAndRun(arg);
    process.exit(r.ok ? 0 : 1);
  } else if (cmd === 'gen' && arg) {
    const nb = JSON.parse(fs.readFileSync(path.resolve(arg), 'utf8'));
    process.stdout.write(genSource(nb));
  } else {
    console.log('usage:');
    console.log('  node tools/notebook.mjs run <path.nb.json>   # build + run a notebook');
    console.log('  node tools/notebook.mjs gen <path.nb.json>   # print generated notebook.tc');
    process.exit(1);
  }
}
