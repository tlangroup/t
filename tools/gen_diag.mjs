#!/usr/bin/env node
// tools/gen_diag.mjs
// 读取 tools/diag_defs.json（诊断单一事实源），生成静态查表代码 src/diag_table.gen.h。
// 消息字符串被编译嵌入二进制（header 由 C/LLVM 后端 include）。
// 同时校验 §1.2 / §1.3 不变量：
//   - code 格式 T-[A-Z]{3}-[EWI]\d{3}
//   - CAT 为三位大写
//   - code 全局唯一
//   - 每 CAT 的编号 NNN 落在该 CAT 的分配区间（保证跨 CAT 区间不重叠 → 全局互斥）
//
// 用法：node tools/gen_diag.mjs [--check]   （--check 仅校验不写文件）

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DEFS = path.join(__dirname, '..', 'tools', 'diag_defs.json');
const OUT = path.join(__dirname, '..', 'src', 'diag_table.gen.h');

// 重排后（选项 c：分类连续、每类从 000 起）每个 CAT 的 NNN 都落在 0..999 内。
// 不再按段隔离——code 含 CAT 前缀，天然全局唯一；这里仅做 0..999 上界校验。
const RANGES = {
  LEX: [0, 999], ICE: [0, 999], PAR: [0, 999], SEM: [0, 999],
  FST: [0, 999], NAM: [0, 999], ANN: [0, 999], DER: [0, 999],
  MOD: [0, 999], MTA: [0, 999], FID: [0, 999], TIM: [0, 999],
  MAT: [0, 999], CLO: [0, 999], FUN: [0, 999], FLG: [0, 999], CLA: [0, 999],
  PIP: [0, 999], RNG: [0, 999], AGT: [0, 999], CDE: [0, 999],
  VEC: [0, 999], DEV: [0, 999], OVL: [0, 999],
};

const CODE_RE = /^T-([A-Z]{3})-([EWI])(\d{3})$/;
const CAT_RE = /^[A-Z]{3}$/;

const checkOnly = process.argv.includes('--check');
const raw = JSON.parse(fs.readFileSync(DEFS, 'utf8'));
const defs = raw.defs;

const errors = [];
const seen = new Set();
const legacySeen = new Set(); // legacy semantic name -> must be globally unique (alias resolution)
const catSeen = {}; // cat -> set of NNN (enforce within-cat uniqueness)

for (const d of defs) {
  const m = CODE_RE.exec(d.code || '');
  if (!m) { errors.push(`bad code format: ${JSON.stringify(d.code)}`); continue; }
  const [, cat, sev, nnnStr] = m;
  const nnn = parseInt(nnnStr, 10);
  if (!CAT_RE.test(cat)) errors.push(`${d.code}: CAT not 3 uppercase`);
  if (!RANGES[cat]) errors.push(`${d.code}: unknown CAT ${cat}`);
  else {
    const [lo, hi] = RANGES[cat];
    if (nnn < lo || nnn > hi) errors.push(`${d.code}: NNN ${nnn} out of CAT range [${lo},${hi}]`);
  }
  const SEVMAP = { error: 'E', warning: 'W', info: 'I' };
  if (SEVMAP[d.sev] !== sev) errors.push(`${d.code}: sev field "${d.sev}" != code sev "${sev}"`);
  if (seen.has(d.code)) errors.push(`duplicate code: ${d.code}`);
  seen.add(d.code);
  if (d.legacy) {
    if (legacySeen.has(d.legacy)) errors.push(`${d.code}: duplicate legacy name "${d.legacy}" (alias collision)`);
    legacySeen.add(d.legacy);
  }
  catSeen[cat + sev] = catSeen[cat + sev] || new Set();
  if (catSeen[cat + sev].has(nnn)) errors.push(`${d.code}: NNN ${nnn} reused within CAT ${cat} (${sev})`);
  catSeen[cat + sev].add(nnn);
  if (!d.name) errors.push(`${d.code}: missing name`);
  if (!d.message) errors.push(`${d.code}: missing message`);
}

if (errors.length) {
  console.error('gen_diag: VALIDATION FAILED:');
  for (const e of errors) console.error('  - ' + e);
  process.exit(1);
}

const byCode = [...defs].sort((a, b) => a.code.localeCompare(b.code));
const esc = (s) => (s == null ? '""' : JSON.stringify(String(s)));

const lines = [];
lines.push('/* AUTO-GENERATED by tools/gen_diag.mjs -- DO NOT EDIT */');
lines.push('/* source of truth: tools/diag_defs.json -- spec: docs/diagnostics.md */');
lines.push('#ifndef T_DIAG_TABLE_GEN_H');
lines.push('#define T_DIAG_TABLE_GEN_H');
lines.push('typedef struct {');
lines.push('  const char* code;');
lines.push('  const char* sev;     /* error | warning | info */');
lines.push('  const char* cat;     /* 3-letter category */');
lines.push('  const char* legacy;  /* old semantic name or "" */');
lines.push('  const char* name;    /* frozen short id */');
lines.push('  const char* message; /* standardized description */');
lines.push('} DiagDef;');
lines.push('');
lines.push('static const DiagDef DIAG_DEFS[] = {');
for (const d of byCode) {
  lines.push('  { ' + esc(d.code) + ', ' + esc(d.sev) + ', ' + esc(d.cat) + ', ' +
    esc(d.legacy || '') + ', ' + esc(d.name) + ', ' + esc(d.message) + ' },');
}
lines.push('};');
lines.push(`#define DIAG_COUNT ${byCode.length}`);

// 双标识别名表：旧语义名 -> 机器码（ratified 决策 #1：新旧同时采用）
// 仅含 legacy != null 的条目；编译器控制参数 -Woff/-Wdeny/-Wallow 两种写法都解析到此表。
lines.push('');
lines.push('/* legacy (old semantic name) -> machine code alias table */');
lines.push('static const struct { const char* legacy; const char* code; } DIAG_LEGACY[] = {');
for (const d of byCode) {
  if (d.legacy) lines.push('  { ' + esc(d.legacy) + ', ' + esc(d.code) + ' },');
}
lines.push('};');
lines.push(`#define DIAG_LEGACY_COUNT ${byCode.filter((d) => d.legacy).length}`);

lines.push('');
lines.push('const DiagDef* diag_find(const char* code);        /* exact machine-code lookup */');
lines.push('const DiagDef* diag_find_any(const char* id);      /* machine code OR legacy name */');
lines.push('#endif /* T_DIAG_TABLE_GEN_H */');
lines.push('');

const out = lines.join('\n');

if (checkOnly) {
  console.log(`gen_diag: --check OK, ${byCode.length} diagnostics valid.`);
} else {
  fs.writeFileSync(OUT, out);
  // category histogram
  const hist = {};
  for (const d of defs) hist[d.cat] = (hist[d.cat] || 0) + 1;
  console.log(`gen_diag: wrote ${OUT}`);
  console.log(`gen_diag: ${byCode.length} diagnostics across ${Object.keys(hist).length} categories`);
  console.log('gen_diag: by category = ' + JSON.stringify(hist));
}
