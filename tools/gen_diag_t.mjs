#!/usr/bin/env node
// tools/gen_diag_t.mjs
// 诊断单一事实源 tools/diag_defs.json -> 生成 t 源码块，替换 src/base.tc 的
// >>> GEN:diagnostics ... <<< GEN:diagnostics 区域。
// 与 src/diag_table.gen.h 同源（都由 gen_diag.mjs / 本脚本从同一 JSON 生成）。
//
// 生成的代码提供：
//   - 平行数组 g_dcode / g_dsev / g_dcat / g_dname / g_dlegacy / g_dnote / g_dmsg（机器码主表）
//   - legacy 别名表 g_leg_name / g_leg_idx（旧语义名 -> 机器码下标）
//   - g_dcount / g_legcount 长度常量（编译期已知，供消费者免 slice_len 遍历）
//   - diag_ensure()   保留为空函数（静态定长数组已编译期初始化，维持调用点兼容）
//   - diag_norm(id)   机器码/旧语义名 -> 规范化机器码（双标识，见 docs/diagnostics.md §1.2.3）
//   - diag_find_idx(code)  机器码 -> 下标
//   - diag_sev(code)  兼容旧接口，返回规范化后的严重度
//
// ⚠ 静态定长数组：所有 g_d* 表均为 [N]T / [M]T 字面量（N=诊断总数，M=含 legacy 数），
// 双后端均编译为静态存储（无堆分配）。消费者遍历改用 g_dcount / g_legcount 长度常量，
// 不得对定长数组调用 slice_len（[N]T→[]T 无隐式转换，会读垃圾长度，见 docs/lifecycle.md）。
//
// 用法：node tools/gen_diag_t.mjs [--check]
//   --check 仅校验 + 报告将要写入的条目数，不写文件。

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const JSON_PATH = path.join(__dirname, '..', 'tools', 'diag_defs.json');
const BASE = path.join(__dirname, '..', 'src', 'base.tc');
const MARKER = 'GEN:diagnostics';

const checkOnly = process.argv.includes('--check');
const raw = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
const defs = [...raw.defs].sort((a, b) => a.code.localeCompare(b.code));

const esc = (s) => JSON.stringify(s == null ? '' : String(s));

// 预计算各列（定长，编译期已知）
const codeArr = [], sevArr = [], catArr = [], nameArr = [], legArr = [], noteArr = [], helpArr = [], msgArr = [];
const legNameArr = [], legIdxArr = [];
defs.forEach((d, i) => {
  codeArr.push(esc(d.code));
  sevArr.push(esc(d.sev));
  catArr.push(esc(d.cat));
  nameArr.push(esc(d.name));
  legArr.push(esc(d.legacy == null ? '' : d.legacy));
  noteArr.push(esc(d.note == null ? '' : d.note));
  helpArr.push(esc(d.help == null ? '' : d.help));
  msgArr.push(esc(d.message == null ? '' : d.message));
  if (d.legacy != null) { legNameArr.push(esc(d.legacy)); legIdxArr.push(String(i)); }
});
const N = codeArr.length;
const M = legNameArr.length;

const lines = [];
lines.push('// >>> ' + MARKER + ' (generated by tools/gen_diag_t.mjs from tools/diag_defs.json -- DO NOT EDIT) >>>');
lines.push('// 诊断码单一事实源：tools/diag_defs.json（与 src/diag_table.gen.h 同源）。');
lines.push('// diag_new 通过 diag_norm 同时接受机器码与旧语义名（双标识，见 docs/diagnostics.md §1.2.3）。');
lines.push('// ⚠ 静态定长数组：[N]T / [M]T 字面量，双后端编译为静态存储（无堆分配）；消费者遍历用');
lines.push('//   g_dcount / g_legcount 长度常量，禁止对定长数组调用 slice_len（[N]T→[]T 无隐式转换，');
lines.push('//   会读垃圾长度，见 docs/lifecycle.md）。');
lines.push('');
lines.push('var g_dcount: i64 = ' + N + ';');
lines.push('var g_legcount: i64 = ' + M + ';');
lines.push('var g_dcode: [' + N + ']string = [' + codeArr.join(', ') + '];');
lines.push('var g_dsev: [' + N + ']string = [' + sevArr.join(', ') + '];');
lines.push('var g_dcat: [' + N + ']string = [' + catArr.join(', ') + '];');
lines.push('var g_dname: [' + N + ']string = [' + nameArr.join(', ') + '];');
lines.push('var g_dlegacy: [' + N + ']string = [' + legArr.join(', ') + '];');
lines.push('var g_dnote: [' + N + ']string = [' + noteArr.join(', ') + '];');
lines.push('var g_dhelp: [' + N + ']string = [' + helpArr.join(', ') + '];');
lines.push('var g_dmsg: [' + N + ']string = [' + msgArr.join(', ') + '];');
lines.push('var g_leg_name: [' + M + ']string = [' + legNameArr.join(', ') + '];');
lines.push('var g_leg_idx: [' + M + ']i64 = [' + legIdxArr.join(', ') + '];');
lines.push('');
lines.push('// 静态定长数组已编译期初始化，无需运行时填充（保留空函数以维持调用点兼容）。');
lines.push('fn diag_ensure() void {');
lines.push('}');
lines.push('');
lines.push('// 机器码/旧语义名 -> 规范化机器码（双标识）。未知码原样返回。');
lines.push('fn diag_norm(id: string) string {');
lines.push('    if (diag_find_idx(id) >= 0) { return id; }');
lines.push('    var i: i64 = 0;');
lines.push('    while (i < g_legcount) {');
lines.push('        if (g_leg_name[i] == id) { return g_dcode[g_leg_idx[i]]; }');
lines.push('        i = i + 1;');
lines.push('    }');
lines.push('    return id;');
lines.push('}');
lines.push('');
lines.push('fn diag_find_idx(code: string) i64 {');
lines.push('    var i: i64 = 0;');
lines.push('    while (i < g_dcount) {');
lines.push('        if (g_dcode[i] == code) { return i; }');
lines.push('        i = i + 1;');
lines.push('    }');
lines.push('    return -1;');
lines.push('}');
lines.push('');
lines.push('// 兼容旧 diag_sev(code)：返回规范化后的严重度（未知码回退 error）。');
lines.push('fn diag_sev(code: string) string {');
lines.push('    var mc: string = diag_norm(code);');
lines.push('    var idx: i64 = diag_find_idx(mc);');
lines.push('    if (idx >= 0) { return g_dsev[idx]; }');
lines.push('    return "error";');
lines.push('}');
lines.push('// <<< ' + MARKER + ' <<<');

const block = lines.join('\n');

// 读取 base.tc：抽出 >>> ... <<< 区域，移除，再插到 diag_new 定义之前
// （确保 g_dcode 等全局在 diag_new 引用之前已声明，规避 t 的"先声明后使用"约束）。
const src = fs.readFileSync(BASE, 'utf8');
const re = new RegExp('// >>> ' + MARKER + '[\\s\\S]*?// <<< ' + MARKER + ' <<<', 'm');
const m = src.match(re);
if (!m) {
  console.error('gen_diag_t: marker not found in ' + BASE);
  process.exit(1);
}
const without = src.replace(re, '');
// ⚠ anchor 必须优先匹配 `pub fn diag_new(`：diag_new 现为 `pub fn diag_new(`，
// 若用 `fn diag_new(` 作锚，indexOf 会命中 `pub ` 之后的 `fn`，插入块后 `pub` 被绑到
// 块首声明、diag_new 反丢 pub（跨模块不可见 → T-MOD-E558）。故优先 `pub fn diag_new(`，
// 回退到 `fn diag_new(` 时若同行前缀为 `pub` 也回退到 `pub` 起点。
let anchor = 'pub fn diag_new(';
let ai = without.indexOf(anchor);
if (ai < 0) {
  anchor = 'fn diag_new(';
  ai = without.indexOf(anchor);
  if (ai >= 0) {
    const ls = without.lastIndexOf('\n', ai) + 1;
    if (without.slice(ls, ai).trim() === 'pub') ai = ls;
  }
}
if (ai < 0) {
  anchor = 'diag_new fn(';
  ai = without.indexOf(anchor);
}
if (ai < 0) {
  console.error('gen_diag_t: anchor "pub fn diag_new(" / "fn diag_new(" / "diag_new fn(" not found in ' + BASE);
  process.exit(1);
}
// 在 anchor 前插入生成块。先吃掉 anchor 之前的尾随空行，保证反复运行幂等
// （否则每跑一次就在块前后多留几个空行，污染 diff）。
const head = without.slice(0, ai).replace(/\n+$/, '\n');
const injected = head + block + '\n\n' + without.slice(ai);

if (checkOnly) {
  console.log(`gen_diag_t: --check OK, ${defs.length} diagnostics (N=${N}, M=${M}), would write to ${BASE}`);
} else {
  fs.writeFileSync(BASE, injected);
  console.log(`gen_diag_t: wrote ${BASE} (${defs.length} diagnostics, N=${N}, M=${M}, block before diag_new)`);
}
