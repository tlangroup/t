#!/usr/bin/env node
// tools/gen_diag_t.mjs
// 诊断单一事实源 tools/diag_defs.json -> 生成 t 源码块，替换 src/base.tc 的
// >>> GEN:diagnostics ... <<< GEN:diagnostics 区域。
// 与 src/diag_table.gen.h 同源（都由 gen_diag.mjs / 本脚本从同一 JSON 生成）。
//
// 生成的代码提供：
//   - 平行数组 g_dcode / g_dsev / g_dcat / g_dname / g_dlegacy / g_dnote（机器码主表）
//   - legacy 别名表 g_leg_name / g_leg_idx（旧语义名 -> 机器码下标）
//   - diag_ensure()   幂等填充
//   - diag_norm(id)   机器码/旧语义名 -> 规范化机器码（双标识，见 docs/diagnostics.md §1.2.3）
//   - diag_find_idx(code)  机器码 -> 下标
//   - diag_sev(code)  兼容旧接口，返回规范化后的严重度
//
// 用法：node tools/gen_diag_t.mjs [--check]
//   --check 仅校验 + 报告将要写入的条目数，不写文件。

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const JSON_PATH = path.join(__dirname, '..', 'tools', 'diag_defs.json');
const BASE = path.join(__dirname, '..', 'src', 'base.tc');
const MARKER = 'GEN:diagnostics';

const checkOnly = process.argv.includes('--check');
const raw = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
const defs = [...raw.defs].sort((a, b) => a.code.localeCompare(b.code));

const esc = (s) => JSON.stringify(s == null ? '' : String(s));

const lines = [];
lines.push('// >>> ' + MARKER + ' (generated by tools/gen_diag_t.mjs from tools/diag_defs.json -- DO NOT EDIT) >>>');
lines.push('// 诊断码单一事实源：tools/diag_defs.json（与 src/diag_table.gen.h 同源）。');
lines.push('// diag_new 通过 diag_norm 同时接受机器码与旧语义名（双标识，见 docs/diagnostics.md §1.2.3）。');
lines.push('');
lines.push('var g_dcode: []string;');
lines.push('var g_dsev: []string;');
lines.push('var g_dcat: []string;');
lines.push('var g_dname: []string;');
lines.push('var g_dlegacy: []string;');
lines.push('var g_dnote: []string;');
lines.push('var g_leg_name: []string;');
lines.push('var g_leg_idx: []i64;');
lines.push('');
lines.push('diag_ensure fn() void {');
lines.push('    if ((slice_len(g_dcode) as i64) > 0) { return; }');
let idx = 0;
for (const d of defs) {
  lines.push('    append(g_dcode, ' + esc(d.code) + ');');
  lines.push('    append(g_dsev, ' + esc(d.sev) + ');');
  lines.push('    append(g_dcat, ' + esc(d.cat) + ');');
  lines.push('    append(g_dname, ' + esc(d.name) + ');');
  lines.push('    append(g_dlegacy, ' + esc(d.legacy || '') + ');');
  lines.push('    append(g_dnote, ' + esc(d.note || '') + ');');
  if (d.legacy) {
    lines.push('    append(g_leg_name, ' + esc(d.legacy) + ');');
    lines.push('    append(g_leg_idx, ' + idx + ');');
  }
  idx++;
}
lines.push('}');
lines.push('');
lines.push('// 机器码/旧语义名 -> 规范化机器码（双标识）。未知码原样返回。');
lines.push('diag_norm fn(id: string) string {');
lines.push('    if ((slice_len(g_dcode) as i64) == 0) { diag_ensure(); }');
lines.push('    if (diag_find_idx(id) >= 0) { return id; }');
lines.push('    var i: i64 = 0;');
lines.push('    while (i < (slice_len(g_leg_name) as i64)) {');
lines.push('        if (g_leg_name[i] == id) { return g_dcode[g_leg_idx[i]]; }');
lines.push('        i = i + 1;');
lines.push('    }');
lines.push('    return id;');
lines.push('}');
lines.push('');
lines.push('diag_find_idx fn(code: string) i64 {');
lines.push('    var i: i64 = 0;');
lines.push('    while (i < (slice_len(g_dcode) as i64)) {');
lines.push('        if (g_dcode[i] == code) { return i; }');
lines.push('        i = i + 1;');
lines.push('    }');
lines.push('    return -1;');
lines.push('}');
lines.push('');
lines.push('// 兼容旧 diag_sev(code)：返回规范化后的严重度（未知码回退 error）。');
lines.push('diag_sev fn(code: string) string {');
lines.push('    if ((slice_len(g_dcode) as i64) == 0) { diag_ensure(); }');
lines.push('    var mc: string = diag_norm(code);');
lines.push('    var idx: i64 = diag_find_idx(mc);');
lines.push('    if (idx >= 0) { return g_dsev[idx]; }');
lines.push('    return "error";');
lines.push('}');
lines.push('// <<< ' + MARKER + ' <<<');

const block = lines.join('\n');

// 读取 base.tc：抽出 >>> ... <<< 区域，移除，再插到 diag_new 定义之前
// （确保 g_dcode 等全局在 diag_new 引用之前已声明，规避 t 的"先声明后使用"约束）。
const src = fs.readFileSync(BASE, 'utf8');
const re = new RegExp('// >>> ' + MARKER + '[\\s\\S]*?// <<< ' + MARKER + ' <<<', 'm');
const m = src.match(re);
if (!m) {
  console.error('gen_diag_t: marker not found in ' + BASE);
  process.exit(1);
}
const without = src.replace(re, '');
const anchor = 'diag_new fn(';
const ai = without.indexOf(anchor);
if (ai < 0) {
  console.error('gen_diag_t: anchor "' + anchor + '" not found in ' + BASE);
  process.exit(1);
}
// 在 anchor 前插入一个空行 + 生成块 + 空行
const injected = without.slice(0, ai) + '\n' + block + '\n' + without.slice(ai);

if (checkOnly) {
  console.log(`gen_diag_t: --check OK, ${defs.length} diagnostics, would write to ${BASE}`);
} else {
  fs.writeFileSync(BASE, injected);
  console.log(`gen_diag_t: wrote ${BASE} (${defs.length} diagnostics, block before diag_new)`);
}
