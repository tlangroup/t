// tools/cstgen.mjs —— CST 代码生成器（S2a 前置；S1 起用）
//
// 定位：CST 的样板代码（kind 枚举 / 名称表 / 映射函数 / 未来的分表与访问者）**一律生成**，
// 禁止手写——手写必然与清单漂移，而漂移在编译器里表现为「静默错编」（最难查的一类）。
// 清单来源唯一：tools/cst_kinds.json（由 tools/cst_kinds_census.mjs 从 src/*.tc 实证抽取）。
//
// 用法：
//   node tools/cstgen.mjs --emit    # 重写 lib/std/rc/cst.tc 的 GEN:kinds 区间
//   node tools/cstgen.mjs --check   # 校验该区间与生成物一致（不一致 exit 1；供门禁断言）
//   node tools/cstgen.mjs --print   # 只打印生成物
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const MANIFEST = join(ROOT, "tools", "cst_kinds.json");
const TARGET = join(ROOT, "lib", "std", "rc", "cst.tc");
const BEGIN = "// >>> GEN:kinds (generated by tools/cstgen.mjs from tools/cst_kinds.json -- DO NOT EDIT) >>>";
const END = "// <<< GEN:kinds <<<";

if (!existsSync(MANIFEST)) {
  console.error("[cstgen] 缺少清单 tools/cst_kinds.json —— 先跑 node tools/cst_kinds_census.mjs");
  process.exit(2);
}
const M = JSON.parse(readFileSync(MANIFEST, "utf8"));

// ── 枚举顺序：先保注册表原序（稳定性/兼容），再追加实证新增项（排序）──
const ordered = [];
const seen = new Set();
for (const k of M.registry) { if (!seen.has(k)) { seen.add(k); ordered.push(k); } }
const extra = M.universe.filter((k) => !seen.has(k)).sort();
for (const k of extra) { seen.add(k); ordered.push(k); }

// ── 常量名：NK_ + UPPER_SNAKE。必须无冲突（冲突 = 生成器硬失败，绝不静默）──
function constName(k) { return "NK_" + k.toUpperCase().replace(/[^A-Z0-9]+/g, "_"); }
const names = new Map();
for (const k of ordered) {
  const c = constName(k);
  if (names.has(c)) {
    console.error(`[cstgen] 常量名冲突：'${k}' 与 '${names.get(c)}' 都映射到 ${c}`);
    process.exit(2);
  }
  names.set(c, k);
}

const N = ordered.length;
const L = [];
L.push(BEGIN);
L.push(`pub var g_nkn_count: i64 = ${N};`);
L.push(`pub var node_kind_names: [${N}]string = [${ordered.map((k) => `"${k}"`).join(", ")}];`);
L.push("");
L.push("// 数值 kind ↔ 名称：tag = 在 node_kind_names 中的下标（双射，无需第二份数据）。");
for (let i = 0; i < N; i++) L.push(`pub const ${constName(ordered[i])}: i64 = ${i};`);
L.push("");
L.push(`pub fn init_node_kinds() void {`);
L.push(`    // 静态定长数组 [N]string 已编译期初始化（见 g_nkn_count），无需运行时 append 填充。`);
L.push(``);
L.push(`}`);
L.push("");
L.push(`pub fn nk_name(t: i64) string {`);
L.push(`    if (t < 0) { return ""; }`);
L.push(`    if (t >= g_nkn_count) { return ""; }`);
L.push(`    return node_kind_names[t];`);
L.push(`}`);
L.push("");
L.push(`// 线性查找（O(N) 次字符串比较）。`);
L.push(`// ⚠ 现状取舍：t 语言层面**没有可用的字符串序比较**（runtime 只有 tll_str_eq，无 strcmp 暴露），`);
L.push(`//   故无法二分；且 is_node_kind 当前零消费点、nk_of_kind 仅作过渡 API。`);
L.push(`//   S2 落地「节点 tag 字段」后，分派变成纯整数比较，本函数的开销自然消失。`);
L.push(`pub fn nk_of_kind(k: string) i64 {`);
L.push(`    var i: i64 = 0;`);
L.push(`    while (i < g_nkn_count) {`);
L.push(`        if (node_kind_names[i] == k) { return i; }`);
L.push(`        i = i + 1;`);
L.push(`    }`);
L.push(`    return -1;`);
L.push(`}`);
L.push("");
L.push(`pub fn is_node_kind(k: string) bool { return nk_of_kind(k) >= 0; }`);
L.push(END);

const block = L.join("\n");

// ── 模式 ──
const mode = process.argv.includes("--check") ? "check" : (process.argv.includes("--emit") ? "emit" : "print");
if (mode === "print") { console.log(block); process.exit(0); }

if (!existsSync(TARGET)) { console.error(`[cstgen] 目标文件不存在：${TARGET}`); process.exit(2); }
const src = readFileSync(TARGET, "utf8");
const bi = src.indexOf(BEGIN);
const ei = src.indexOf(END);
if (bi < 0 || ei < 0) { console.error("[cstgen] 目标文件缺少 GEN:kinds 标记，无法定位区间"); process.exit(2); }

const cur = src.slice(bi, ei + END.length);
if (mode === "check") {
  if (cur === block) { console.log(`[cstgen] --check OK（${N} 个 kind，区间一致）`); process.exit(0); }
  console.error(`[cstgen] --check FAIL：GEN:kinds 区间与清单不一致（清单 ${N} 个 kind）。跑 node tools/cstgen.mjs --emit 重新生成。`);
  process.exit(1);
}

const out = src.slice(0, bi) + block + src.slice(ei + END.length);
writeFileSync(TARGET, out);
console.log(`[cstgen] 已重写 GEN:kinds：${N} 个 kind（注册表 ${M.registry.length} + 实证新增 ${extra.length}）`);
console.log(`[cstgen] 新增项：${extra.join(", ")}`);
