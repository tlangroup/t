// tools/cstgen.mjs —— CST 代码生成器（S2a 前置；S1 起用）
//
// 定位：CST 的样板代码（kind 枚举 / 名称表 / 映射函数 / 分表与访问者）**一律生成**，
// 禁止手写——手写必然与清单漂移，而漂移在编译器里表现为「静默错编」（最难查的一类）。
//
// 两个生成目标：
//   1) GEN:kinds        → lib/std/rc/cst.tc   （纯类型/常量/查询函数，库模块，无运行期可变全局）
//   2) GEN:node-structs → src/base.tc          （**逐字段独立 typed 切片**的 struct-of-arrays 分表
//                                                + 双写登记 cst_register_X + g_node_nref 平行数组；
//                                                落在主程序模块，规避库全局跳过 t__ginit 静默清零，§4.14.7）
//
// 用法：
//   node tools/cstgen.mjs --emit    # 重写两个 GEN 区间
//   node tools/cstgen.mjs --check   # 校验两区间与清单一致（不一致 exit 1；供门禁断言）
//   node tools/cstgen.mjs --print   # 只打印生成物
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const KINDS_MANIFEST = join(ROOT, "tools", "cst_kinds.json");
const NODES_MANIFEST = join(ROOT, "tools", "cst_nodes.json");
const KINDS_TARGET = join(ROOT, "lib", "std", "rc", "cst.tc");
const NODES_TARGET = join(ROOT, "src", "base.tc");
const KINDS_BEGIN = "// >>> GEN:kinds (generated by tools/cstgen.mjs from tools/cst_kinds.json -- DO NOT EDIT) >>>";
const KINDS_END = "// <<< GEN:kinds <<<";
const NODES_BEGIN = "// >>> GEN:node-structs (generated by tools/cstgen.mjs from tools/cst_nodes.json -- DO NOT EDIT) >>>";
const NODES_END = "// <<< GEN:node-structs <<<";

// ── 目标 1：kind 枚举 ──
if (!existsSync(KINDS_MANIFEST)) {
  console.error("[cstgen] 缺少清单 tools/cst_kinds.json —— 先跑 node tools/cst_kinds_census.mjs");
  process.exit(2);
}
const MK = JSON.parse(readFileSync(KINDS_MANIFEST, "utf8"));
const ordered = [];
const seen = new Set();
for (const k of MK.registry) { if (!seen.has(k)) { seen.add(k); ordered.push(k); } }
const extra = MK.universe.filter((k) => !seen.has(k)).sort();
for (const k of extra) { seen.add(k); ordered.push(k); }

function constName(k) { return "NK_" + k.toUpperCase().replace(/[^A-Z0-9]+/g, "_"); }
const names = new Map();
for (const k of ordered) {
  const c = constName(k);
  if (names.has(c)) {
    console.error(`[cstgen] 常量名冲突：'${k}' 与 '${names.get(c)}' 都映射到 ${c}`);
    process.exit(2);
  }
  names.set(c, k);
}
const N = ordered.length;
const L = [];
L.push(KINDS_BEGIN);
L.push(`pub var g_nkn_count: i64 = ${N};`);
L.push(`pub var node_kind_names: [${N}]string = [${ordered.map((k) => `"${k}"`).join(", ")}];`);
L.push("");
L.push("// 数值 kind ↔ 名称：tag = 在 node_kind_names 中的下标（双射，无需第二份数据）。");
for (let i = 0; i < N; i++) L.push(`pub const ${constName(ordered[i])}: i64 = ${i};`);
L.push("");
L.push(`pub fn init_node_kinds() void {`);
L.push(`    // 静态定长数组 [N]string 已编译期初始化（见 g_nkn_count），无需运行时 append 填充。`);
L.push(``);
L.push(`}`);
L.push("");
L.push(`pub fn nk_name(t: i64) string {`);
L.push(`    if (t < 0) { return ""; }`);
L.push(`    if (t >= g_nkn_count) { return ""; }`);
L.push(`    return node_kind_names[t];`);
L.push(`}`);
L.push("");
L.push(`// 线性查找（O(N) 次字符串比较）。`);
L.push(`// ⚠ 现状取舍：t 语言层面**没有可用的字符串序比较**（runtime 只有 tll_str_eq，无 strcmp 暴露），`);
L.push(`//   故无法二分；且 is_node_kind 当前零消费点、nk_of_kind 仅作过渡 API。`);
L.push(`//   S2 落地「节点 tag 字段」后，分派变成纯整数比较，本函数的开销自然消失。`);
L.push(`pub fn nk_of_kind(k: string) i64 {`);
L.push(`    var i: i64 = 0;`);
L.push(`    while (i < g_nkn_count) {`);
L.push(`        if (node_kind_names[i] == k) { return i; }`);
L.push(`        i = i + 1;`);
L.push(`    }`);
L.push(`    return -1;`);
L.push(`}`);
L.push("");
L.push(`pub fn is_node_kind(k: string) bool { return nk_of_kind(k) >= 0; }`);
L.push(KINDS_END);
const kindsBlock = L.join("\n");

// ── 目标 2：分表（pilot 子集，逐字段独立 typed 全局切片）──
// S2 落地说明：S1b 种子编译器在 base.tc 内同时定义「全局结构体(切片字段) + 多个函数」会陷入
// 语义分析失控递归（实证见 docs/compiler/cst-design-v2.md §0.12）。故此处只生成**独立 typed
// 全局切片**（SoA 逐字段），不生成 CstTables 结构体，也不生成 cst_register_* 登记函数
// （登记函数与辅助函数 mk_noderef/nr_*/Span/mk_span 延后到 S2b 修种子后落地）。
// 当前仅建立与 nodes[] 按 id 对齐的平行 NodeRef 数组 g_node_nref；cst_register_* 缺失期间
// 各 tbl_* 仅声明不写入，平行数组正确性由 node_new 双写保证。
if (!existsSync(NODES_MANIFEST)) {
  console.error("[cstgen] 缺少清单 tools/cst_nodes.json");
  process.exit(2);
}
const NM = JSON.parse(readFileSync(NODES_MANIFEST, "utf8"));

function recName(kind) {
  return kind.split("_").map((s) => (s.length ? s[0].toUpperCase() + s.slice(1) : s)).join("");
}

const NL = [];
NL.push(NODES_BEGIN);
NL.push(`// ── S2：按 kind 分表（struct-of-arrays）的运行时子集 ──`);
NL.push(`// 由 tools/cstgen.mjs 依据 tools/cst_nodes.json 生成：每个 kind 一组`);
NL.push(`// 逐字段独立 typed 全局切片 tbl_<RecK>_<field> + Rec<K> 结构 + cst_register_<RecK> 双写登记`);
NL.push(`// + cst_get_<RecK> 读取。运行时可变全局刻意落在主程序模块 base.tc（§4.14.7：库模块`);
NL.push(`// 跳过 t__ginit，可变全局会被静默清零）。旧 nodes[] 仍是真相源，本区为其 SoA 镜像。`);
NL.push(``);
NL.push(`// 平行 NodeRef 数组 g_node_nref（默认 0 = 未登记），node_new 双写保证正确。`);
NL.push(`pub var g_node_nref: []u64;`);
NL.push(`pub fn cst_nref_of(id: i64) u64 {`);
NL.push(`    if (id < 0 || id >= slice_len(g_node_nref)) { return 0; }`);
NL.push(`    return g_node_nref[id];`);
NL.push(`}`);
NL.push(``);
let genKinds = 0;
for (const kind of NM.pilot) {
  const spec = NM.nodes[kind];
  if (!spec) continue;
  const R = spec.rec;
  const fields = spec.fields || []; // [[name, type], ...]
  if (!R) continue;
  genKinds++;
  // 逐字段 typed 全局切片 + Rec<K> 结构（仅当有字段）
  if (fields.length > 0) {
    for (const [f, t] of fields) NL.push(`pub var tbl_${R}_${f}: []${t};`);
    NL.push(`pub struct ${R} {`);
    for (const [f, t] of fields) NL.push(`    ${f}: ${t};`);
    NL.push(`}`);
  }
  // 双写登记：mk_* 在创建节点后调用，按创建顺序 append（零字段 kind 退化为 no-op）
  const sig = fields.map(([f, t]) => `${f}: ${t}`).join(", ");
  NL.push(`pub fn cst_register_${R}(${sig}) void {`);
  for (const [f] of fields) NL.push(`    append(tbl_${R}_${f}, ${f});`);
  NL.push(`}`);
  // 读取（仅当有字段）
  if (fields.length > 0) {
    NL.push(`pub fn cst_get_${R}(i: i64) ${R} {`);
    NL.push(`    var r: ${R};`);
    for (const [f] of fields) NL.push(`    r.${f} = tbl_${R}_${f}[i];`);
    NL.push(`    return r;`);
    NL.push(`}`);
  }
  NL.push(``);
}
NL.push(NODES_END);
const nodesBlock = NL.join("\n");

// ── 模式 ──
const mode = process.argv.includes("--check") ? "check" : (process.argv.includes("--emit") ? "emit" : "print");
if (mode === "print") { console.log(kindsBlock + "\n\n" + nodesBlock); process.exit(0); }

function replaceRegion(src, begin, end, block, label) {
  if (!existsSync(src)) { console.error(`[cstgen] 目标文件不存在：${src}`); process.exit(2); }
  const s = readFileSync(src, "utf8");
  const bi = s.indexOf(begin);
  const ei = s.indexOf(end);
  if (bi < 0 || ei < 0) { console.error(`[cstgen] ${label} 缺少标记，无法定位区间`); process.exit(2); }
  const cur = s.slice(bi, ei + end.length);
  return { s, cur, bi, ei, out: s.slice(0, bi) + block + s.slice(ei + end.length) };
}

const k = replaceRegion(KINDS_TARGET, KINDS_BEGIN, KINDS_END, kindsBlock, "GEN:kinds");
const n = replaceRegion(NODES_TARGET, NODES_BEGIN, NODES_END, nodesBlock, "GEN:node-structs");

if (mode === "check") {
  let ok = true;
  if (k.cur !== kindsBlock) {
    ok = false;
    console.error(`[cstgen] --check FAIL：GEN:kinds 区间与清单不一致（清单 ${N} 个 kind）。跑 node tools/cstgen.mjs --emit 重新生成。`);
  }
  if (n.cur !== nodesBlock) {
    ok = false;
    console.error(`[cstgen] --check FAIL：GEN:node-structs 区间与 cst_nodes.json 不一致。跑 node tools/cstgen.mjs --emit 重新生成。`);
  }
  if (ok) {
    console.log(`[cstgen] --check OK（kinds ${N} 个；node-structs ${NM.pilot.length} 个 pilot kind）`);
    process.exit(0);
  }
  process.exit(1);
}

writeFileSync(KINDS_TARGET, k.out);
writeFileSync(NODES_TARGET, n.out);
console.log(`[cstgen] 已重写 GEN:kinds（${N} 个 kind，注册表 ${MK.registry.length} + 实证新增 ${extra.length}）`);
console.log(`[cstgen]   新增项：${extra.join(", ")}`);
console.log(`[cstgen] 已重写 GEN:node-structs（pilot ${NM.pilot.length} 个 kind：${NM.pilot.join(", ")}）`);
